# Integer formatting (decimal)
number = 12345
print(f"Decimal: {number:d}")

# Binary formatting
print(f"Binary: {number:b}")

# Octal formatting
print(f"Octal: {number:o}")

# Hexadecimal formatting (lowercase)
print(f"Hexadecimal (lowercase): {number:x}")

# Hexadecimal formatting (uppercase)
print(f"Hexadecimal (uppercase): {number:X}")

# Floating-point formatting (fixed-point)
pi = 3.14159
print(f"Pi (fixed-point): {pi:.2f}")

# Floating-point formatting (exponential)
print(f"Pi (exponential): {pi:e}")

# String formatting
message = "Hello, Python!"
print(f"Message: {message}")
